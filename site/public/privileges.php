/**
 * Идентификатор <template> для вещи, которую показывают отдельно.
 *
 * Строится из имени модели, а не из названия: названия русские и владелец их
 * правит, а имя модели — это имя файла, оно латинское и заведомо неповторимое.
 * Свою приставку модели срезаем, иначе выходит «tpl-knife-knife-claw».
 *
 * ⚠️ ЭТА СТРОКА ОБЯЗАНА СОВПАСТЬ С id САМОГО <template> БУКВА В БУКВУ. Не
 * совпадёт — просмотрщик шаблона не найдёт, правая колонка окажется пустой, и
 * окно покажет одну модель. Молча: ни ошибки в консоли, ни пустого места в
 * разметке — колонка просто прячется. Поэтому и ссылка, и сам шаблон зовут эту
 * функцию, а строку руками не пишет никто.
 */
function panel_id($kind, $model)
{
    $cut = strpos($model, '-');
    return 'tpl-' . $kind . '-' . ($cut === false ? $model : substr($model, $cut + 1));
}

/*

-- Обновление ДЕЙСТВУЮЩЕЙ базы под перекройку 12 августа 2026.
--
-- Что меняется по сути: админка перестала быть добавкой к уровню и стала
-- отдельным товаром СО СВОИМ СРОКОМ. Раньше её буквы лежали в `access` вместе
-- с буквами уровня, а помнил о ней столбец `has_admin`; теперь у неё свои
-- `admin_access` и `admin_until`, и истёкший срок уровня больше не уносит с
-- собой оплаченную отдельно админку. Заодно заводится таблица новостей.
--
-- Для ЧИСТОЙ установки этот файл не нужен: там schema.sql, он уже приведён к
-- итоговому виду. Здесь — только то, чем догнать базу, где уже лежат живые
-- привилегии и заказы.
--
--     mysqldump -h ... -u ... -p <база> > before-2026-08-12.sql   # СНАЧАЛА ЭТО
--     mysql     -h ... -u ... -p <база> < migrate-2026-08-12.sql
--
-- Дамп здесь не ради порядка: шаг 7 удаляет столбец, взять который потом будет
-- неоткуда.
--
-- Выполняемых запросов в файле ровно семь, по числу шагов (плюс SET NAMES в
-- начале). Всё остальное — комментарии и проверочные запросы, закомментированные
-- намеренно: их запускают руками и глазами читают ответ.
--
-- ⚠️ ФАЙЛ ВЫПОЛНЯЕТСЯ РОВНО ОДИН РАЗ — И ЦЕЛИКОМ, ПОДРЯД.
-- «Один раз» — потому что MySQL 5.7 и 8.0 не знают ADD COLUMN IF NOT EXISTS:
-- второй прогон упадёт на шаге 2 с «Duplicate column name 'admin_access'», а до
-- этого успеет выполнить шаг 1. «Подряд» — потому что между шагом 4 и шагом 6
-- буквы админки из `access` уже вычищены, а представления, которое подставит их
-- обратно из `admin_access`, ещё нет: в этот промежуток купившие админку
-- остаются без прав. Промежуток должен быть длиной в секунду, а не в перекур.
--
-- ⚠️ ОБЕРНУТЬ ВСЁ В ТРАНЗАКЦИЮ НЕЛЬЗЯ. ALTER TABLE и CREATE TABLE в MySQL
-- фиксируют текущую транзакцию сами, неявным COMMIT, так что START TRANSACTION
-- здесь — самообман: после сбоя откатывать будет нечего. Отсюда и требование
-- дампа, и карта шагов ниже.
--
-- ⚠️ Миграцию делают при закрытом сайте. Не из вежливости: пока она идёт, база
-- наполовину в старом виде, наполовину в новом, и покупка, попавшая в этот
-- промежуток, ляжет неизвестно как.
--
-- ── выполнялся ли этот файл уже? ────────────────────────────────────────────
--
--     SHOW COLUMNS FROM `zm_privileges` LIKE 'admin_until';
--
-- Пусто — файл не выполнялся ни разу, начинайте с начала. Строка есть — шаг 2
-- уже прошёл, и надо выяснить, где именно всё оборвалось:
--
--   шаг  что делает                проверка, выполнен ли он
--   ───  ────────────────────────  ─────────────────────────────────────────────
--    1   таблица zm_news           SHOW TABLES LIKE 'zm_news';
--                                  есть строка — сделан
--    2   два столбца привилегий    SHOW COLUMNS FROM `zm_privileges` LIKE 'admin_until';
--                                  есть строка — сделан
--    3   перенос has_admin         SELECT COUNT(*) FROM `zm_privileges`
--                                   WHERE `has_admin` = 1 AND `admin_access` = '';
--                                  ноль — сделан
--    4   вычистка букв админки     SELECT COUNT(*) FROM `zm_privileges`
--                                   WHERE `has_admin` = 1 AND `access` REGEXP '[bcdeiju]';
--                                  ноль — сделан
--    5   kind у заказов            SHOW COLUMNS FROM `zm_orders` LIKE 'kind';
--                                  в Type видно 'admin' — сделан
--    6   представление zm_admins   SHOW CREATE VIEW `zm_admins`;
--                                  упоминается admin_access — сделан
--    7   has_admin убран           SHOW COLUMNS FROM `zm_privileges` LIKE 'has_admin';
--                                  пусто — сделан
--
-- Оборвалось — выполните ОСТАВШИЕСЯ шаги по порядку, начиная с первого
-- несделанного, а не файл целиком. Шаги 1, 3, 4, 5 и 6 повторный запуск
-- переживают молча (IF NOT EXISTS, UPDATE по тому же условию, MODIFY, CREATE OR
-- REPLACE); шаги 2 и 7 — не переживают, они и есть то самое «ровно один раз».
--
-- ⚠️ У безобидности повторного шага 3 есть срок годности: он перезаписывает
-- `admin_until` сроком уровня. Пока сайт закрыт и админку по-новому ещё никто не
-- покупал, повтор ничего не меняет; после первой продажи админки повтор укоротит
-- оплаченное до срока уровня. Ещё один довод доделать миграцию за один раз.
--
-- ⚠️ Проверки шагов 3 и 4 спрашивают `has_admin`. После шага 7 спрашивать станет
-- нечего — и это правильно: после шага 7 работа закончена.

SET NAMES utf8mb4;

-- ── 1. таблица новостей ─────────────────────────────────────────────────────
--
-- Игрового сервера она не касается вовсе: её читают только страницы сайта.
-- Определение слово в слово повторяет schema.sql — база после миграции обязана
-- быть неотличима от базы, поставленной начисто, иначе следующая правка схемы
-- напишется под одну из двух и сломает вторую.
--
-- Единственный шаг с настоящим IF NOT EXISTS: таблица либо создаётся, либо
-- запрос молча ничего не делает.

CREATE TABLE IF NOT EXISTS `zm_news` (
  `id`           INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `title`        VARCHAR(120) NOT NULL,
  -- ОБЫЧНЫЙ ТЕКСТ, никакого HTML. Разметку собирает news_html(), и собирает
  -- она её из уже экранированного текста — потому в базе и лежит то, что автор
  -- набрал, буква в букву. Пусти сюда HTML — и редактор новостей станет
  -- дырой, через которую в чужой браузер попадает чужой скрипт.
  `body`         TEXT         NOT NULL,
  `author`       VARCHAR(64)  NOT NULL DEFAULT '',
  `created_at`   DATETIME     NOT NULL,
  `updated_at`   DATETIME         NULL,
  -- Одно поле на два дела: NULL — черновик, дата — новость видна, и по ней же
  -- порядок в ленте. Отдельного «опубликовано: да/нет» нет НАМЕРЕННО: два
  -- поля, отвечающих за одно состояние, рано или поздно разойдутся, и тогда
  -- черновик всплывёт на главной либо готовая новость не покажется никому.
  `published_at` DATETIME         NULL,
  PRIMARY KEY (`id`),
  KEY `published_at` (`published_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Новости сайта: лента на главной и архив';

-- ── 2. два новых столбца у привилегий ───────────────────────────────────────
--
-- Одним запросом, а не двумя: таблица перестраивается один раз вместо двух, и —
-- что важнее для ночного починщика — «наполовину выполненного шага 2» не
-- бывает. Либо оба столбца появились, либо ни одного.
--
-- AFTER здесь только затем, чтобы SHOW CREATE TABLE совпадал со schema.sql.
-- Работе порядок столбцов безразличен, а вот сверять глазами два разных порядка
-- в три часа ночи — лишняя работа на ровном месте.
--
-- ⚠️ DEFAULT '' у `admin_access` — не украшение. Существующие строки должны
-- получить именно пустую строку: пусто означает «админки нет вовсе». NULL
-- означал бы «неизвестно», такого состояния в нашей модели нет, а код (и
-- grant.php, и представление) сравнивает ровно с '' — с NULL это сравнение
-- всегда неверно, и записи молча выпали бы из выдачи.

ALTER TABLE `zm_privileges`
  ADD COLUMN `admin_access` VARCHAR(31) NOT NULL DEFAULT '' AFTER `tier`,
  ADD COLUMN `admin_until`  DATETIME         NULL           AFTER `expires_at`;

-- ── 3. перенос: кому админка уже выдана ─────────────────────────────────────
--
-- 'bcdeiju' — это ADMIN_FLAGS из private/app/tiers.php, переписанная сюда
-- руками: спросить у PHP база не умеет. Сверьте буквы глазами, прежде чем
-- запускать, — здесь они попадут в права живых людей.
--
-- `admin_until` = `expires_at`: у старой записи срок был ОДИН на всё. Отдав
-- админке тот же самый срок, мы ничего не дарим и ничего не отбираем — она
-- кончится ровно тогда, когда кончилась бы и раньше. NULL перенесётся как NULL,
-- и вечная привилегия останется с вечной админкой.
--
-- ⚠️ Условие `has_admin` = 1 — то же самое, что у шага 4, и это не совпадение,
-- а требование: см. длинное объяснение там.

UPDATE `zm_privileges`
   SET `admin_access` = 'bcdeiju',
       `admin_until`  = `expires_at`
 WHERE `has_admin` = 1;

-- ── 4. вычистка букв админки из access ──────────────────────────────────────
--
-- Убираем ровно семь букв админки: b c d e i j u. Буквы уровня — t s q p o — в
-- списке отсутствуют, и это единственная причина, по которой такая вычистка
-- вообще возможна: наборы не пересекаются.
--
-- ⚠️ УСЛОВИЕ ЗДЕСЬ ОБЯЗАНО СОВПАДАТЬ С УСЛОВИЕМ ШАГА 3, БУКВА В БУКВУ. Буквы не
-- удаляются, а ПЕРЕЕЗЖАЮТ: строка, которой шаг 3 положил их в `admin_access`,
-- здесь теряет их из `access`, и для игрового сервера сумма не меняется —
-- представление склеит обе половины обратно. Расширь мы условие здесь хоть на
-- одну строку сверх шага 3 — эта строка потеряла бы права молча, без ошибки и
-- без следа в журнале.
--
-- ⚠️ ЗАПИСИ СО СВОИМИ ФЛАГАМИ ИЗ ПАНЕЛИ — ТОТ САМЫЙ ОТДЕЛЬНЫЙ СЛУЧАЙ. У
-- владельца в `access` лежит весь алфавит AMXX, у кого-то ещё — свой набор букв,
-- выданный руками. Вычистка отобрала бы у них кик, бан, слей, админ-чат,
-- голосования, резерв места и админ-меню — права, которых никто не отбирал, и
-- заметил бы это владелец на сервере, а не здесь.
--
-- Признак таких записей не изобретён, а взят у кода: public/admin/api.php шлёт
--
--     'with_admin' => $custom === '' && !empty($body['admin'])
--
-- то есть админку панель добавляет ТОЛЬКО при пустых своих флагах. Значит у
-- записи со своими флагами `has_admin` = 0 всегда — и условие `has_admin` = 1
-- обходит их стороной само, без единой оговорки. `admin_access` у них остаётся
-- пустым, представление отдаст их `access` как есть, буква в букву.
--
-- Второй признак, `tier` IS NULL, в одиночку сюда не годится: у записи с полными
-- правами есть буква «o», а tier_of() по ней выдаёт «Создателя», и `tier` там
-- как раз НЕ NULL. Поэтому решает `has_admin`, а `tier` — только для глаз.
--
-- Посмотреть на эти записи ДО запуска (запрос ничего не меняет):
--
--     SELECT `auth`, `tier`, `has_admin`, `access` FROM `zm_privileges`
--      WHERE `has_admin` = 0 AND `access` REGEXP '[bcdeiju]';
--
-- Это и есть полный список тех, кого вычистка не тронет. Если в нём окажется
-- человек, которому админка досталась как ТОВАР, а не своими флагами, —
-- разберитесь с ним руками и до запуска файла: после шага 7 отличить одно от
-- другого будет уже нечем.

UPDATE `zm_privileges`
   SET `access` = REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(
                    `access`, 'b', ''), 'c', ''), 'd', ''), 'e', ''),
                    'i', ''), 'j', ''), 'u', '')
 WHERE `has_admin` = 1;

-- ── 5. вид заказа: появляется «админка» ─────────────────────────────────────
--
-- ⚠️ MODIFY переписывает определение столбца ЦЕЛИКОМ. NOT NULL и DEFAULT 'tier'
-- повторены здесь не для красоты: не напиши их — они пропадут, и заказ без явно
-- указанного вида станет заказом с видом NULL.
--
-- 'admin' дописан В КОНЕЦ списка намеренно. ENUM хранится номером значения, и
-- пока новое значение добавляется последним, номера уже лежащих заказов не
-- меняются, а MySQL правит только определение столбца, не трогая строки. Вставь
-- кто-нибудь 'admin' в середину — это уже перестройка всей таблицы со своим
-- временем и своими рисками.
--
-- Столбец `with_admin` в zm_orders НЕ УДАЛЯЕТСЯ и удалён быть не должен: в нём
-- история старых заказов, где админка шла добавкой к уровню. Панель показывает
-- его у заказов, где он равен 1, и по таким заказам админку выдают руками — см.
-- предупреждение в apply_order().

ALTER TABLE `zm_orders`
  MODIFY COLUMN `kind` ENUM('tier','packs','admin') NOT NULL DEFAULT 'tier';

-- ── 6. представление, которое читает игровой сервер ─────────────────────────
--
-- То же самое определение, что в schema.sql; полное объяснение, почему буквы
-- склеиваются на лету и почему `auth` и `password` отдаются двоичными, — там же.
-- Коротко: сроков теперь два, они независимы, и строка попадает серверу, пока
-- жив хотя бы один; мёртвая половина просто не добавляет своих букв.
--
-- Шаг обязан идти ПОСЛЕ шага 2 — иначе «Unknown column 'admin_access' in field
-- list» — и как можно ближе к шагу 4: между ними админки на сервере нет ни у
-- кого (см. шапку файла).
--
-- ⚠️ НЕ ЗАМЕНЯЙТЕ ЭТО НА DROP VIEW + CREATE VIEW. Если между двумя запросами на
-- игровом сервере сменится карта, admin_sql.amxx выполнит свой
-- «CREATE TABLE IF NOT EXISTS zm_admins», имя окажется свободно, и он заведёт
-- ПУСТУЮ ТАБЛИЦУ. Представление поверх неё уже не ляжет («is not of type VIEW»),
-- а сервер останется без единого администратора. Так уже было при первом
-- запуске. CREATE OR REPLACE делает подмену одним движением, и щели нет.

CREATE OR REPLACE VIEW `zm_admins` AS
  SELECT CAST(`auth` AS BINARY) AS `auth`, CAST(`password` AS BINARY) AS `password`,
         CONCAT(
           IF(`access` <> ''       AND (`expires_at`  IS NULL OR `expires_at`  > NOW()), `access`,       ''),
           IF(`admin_access` <> '' AND (`admin_until` IS NULL OR `admin_until` > NOW()), `admin_access`, '')
         ) AS `access`,
         `account` AS `flags`
  FROM `zm_privileges`
  WHERE (`access` <> ''       AND (`expires_at`  IS NULL OR `expires_at`  > NOW()))
     OR (`admin_access` <> '' AND (`admin_until` IS NULL OR `admin_until` > NOW()));

-- ── 7. и только теперь — прощание с has_admin ───────────────────────────────
--
-- ⚠️⚠️ ЭТОТ ШАГ ПОСЛЕДНИЙ, И ЭТО НЕ ВОПРОС ВКУСА. `has_admin` — единственное
-- место в базе, которое помнит, КОМУ админка была выдана. Урони его до шага 3 —
-- и сведения исчезнут навсегда, без всякой возможности их восстановить: в
-- `access` буквы админки перемешаны с буквами уровня, а у записей со своими
-- флагами ровно те же буквы стоят сами по себе и означают совсем другое.
-- Отличить купленную админку от своих флагов будет уже нечем — останется
-- поднимать zm_audit и заказы и разбирать вручную, по одному человеку.
--
-- ⚠️ Если файл оборвался ДО этого шага — беды нет: сайт работает на новых
-- столбцах, а `has_admin` просто перестал обновляться и с этой минуты врёт.
-- Доделайте шаг, когда сможете, сверившись по карте в шапке, что шаги 3 и 4
-- действительно прошли: их проверки спрашивают `has_admin`, и после этого шага
-- спрашивать станет нечего.
--
-- ⚠️ Но и тянуть нельзя. Новый код в INSERT этот столбец не перечисляет. Если у
-- него NOT NULL без DEFAULT (проверьте: SHOW CREATE TABLE `zm_privileges`), то в
-- строгом режиме выдача новой привилегии будет падать с «Field 'has_admin'
-- doesn't have a default value» — и никакой связи с миграцией по этой ошибке не
-- видно.

ALTER TABLE `zm_privileges` DROP COLUMN `has_admin`;

-- ── что проверить, когда всё прошло ─────────────────────────────────────────
--
-- 1. Определения совпали со schema.sql — иначе следующая правка схемы напишется
--    под одну базу и сломает другую:
--
--        SHOW CREATE TABLE `zm_privileges`;
--        SHOW CREATE TABLE `zm_orders`;
--        SHOW CREATE VIEW  `zm_admins`;
--
-- 2. Представление отдаёт правильные буквы в четырёх случаях: жив только
--    уровень, жива только админка, живы оба, не жив ни один (строки нет вовсе):
--
--        SELECT `auth`, `access`, `flags` FROM `zm_admins` ORDER BY `auth`;
--
--    Повторов букв быть не должно: наборы t s q p o и b c d e i j u не
--    пересекаются, и «tt» в выдаче означало бы, что где-то буквы задвоились.
--
-- 3. Число живых записей не изменилось. Сравните с тем, что было в дампе: людей,
--    у которых права пропали, миграция оставить не имеет права.
--
-- 4. Права доедут до игрового сервера сами, со сменой карты. Хотите сразу —
--    кнопка перезагрузки админов в панели (она же rcon_reload_admins()).

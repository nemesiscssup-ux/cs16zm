/**
 * Data-атрибуты окна просмотра — отдельно от разметки.
 *
 * Вынесены из viewer() потому, что щёлкать по модели теперь может не только
 * само окошко: в витрине привилегий кликабельна карточка целиком, и атрибуты
 * висят на ней. Просмотрщик читает их одинаково, кто бы их ни носил.
 *
 * Пустые пропускаются: атрибут с пустым значением просмотрщик всё равно
 * считает заданным, и, например, data-panel="" увёл бы его искать <template>
 * с пустым идентификатором.
 *
 * $extra   — что ещё можно посмотреть отсюда же: массив
 *            [['id' => 'knife-claw', 'name' => 'Коготь', 'desc' => '...'], ...].
 * $panelId — идентификатор <template> для правой колонки окна.
 */
function viewer_attrs($modelId, $title = '', $desc = '', $extra = null, $panelId = '')
{
    $attrs = '';
    if ($modelId) {
        $attrs .= ' data-model="' . h($modelId) . '"';
    }
    if ($title !== '') {
        $attrs .= ' data-title="' . h($title) . '"';
    }
    if ($desc !== '') {
        $attrs .= ' data-desc="' . h($desc) . '"';
    }
    if ($extra) {
        $attrs .= ' data-extra="' . h(json_encode(array_values($extra), JSON_UNESCAPED_UNICODE)) . '"';
    }
    if ($panelId !== '') {
        $attrs .= ' data-panel="' . h($panelId) . '"';
    }
    return $attrs;
}

/**
 * Картинка модели без своего окна: щёлкать будет карточка снаружи.
 *
 * ⚠️ ИМЕННО БЕЗ role="button" И БЕЗ data-атрибутов. Карточка уровня в витрине
 * кликабельна целиком, и вложить в неё второй элемент с ролью кнопки нельзя:
 * получается кнопка внутри кнопки, по которой ни мышь, ни клавиатура не
 * работают предсказуемо — щелчок по картинке всплывает и открывает окно
 * дважды, Tab останавливается на обеих, а Enter на внутренней срабатывает
 * то за неё, то за карточку. Надписи «смотреть в 3D» здесь тоже нет: про
 * щелчок говорит сама карточка.
 *
 * ⚠️ И БЕЗ ОБЁРТКИ .viewer. Та рамка рассчитана на окошко, которое само себе
 * карточка: у неё своя высота, свой фон и своя рамка в пиксель. Внутри
 * .tier-card она дала бы вторую рамку поверх первой и вторую подложку поверх
 * второй, а высоту карточки стал бы задавать не стиль витрины, а .viewer.
 * Поэтому здесь голый <img>, и стиль берёт его по тегу — см. правило
 * «.tier-card img» в site.css.
 *
 * Пустой идентификатор — не ошибка: у части вещей моделей нет, и тогда лучше
 * ничего, чем пустая рамка.
 */
function model_img($modelId, $class = '')
{
    if (!$modelId) {
        return '';
    }

    return '<img' . ($class === '' ? '' : ' class="' . h($class) . '"')
        . ' src="models/' . h($modelId) . '.png?v=' . h(ZM_ASSET_V) . '" alt="" loading="lazy">';
}

/**
 * Окошко модели на карточке: картинка, по щелчку открывающая просмотр.
 *
 * Показывает ЗАРАНЕЕ НАРИСОВАННУЮ картинку, а живой трёхмерный просмотр
 * открывается по щелчку — один на всю страницу.
 *
 * ⚠️ ТАК СДЕЛАНО НЕ ОТ ЛЕНИ. Раньше каждая карточка держала своё окно WebGL, а
 * браузер даёт их около шестнадцати: на странице привилегий их было за
 * двадцать, и у первых карточек контекст отбирался — вместо модели оставался
 * белый квадрат, стоило пролистать вниз и вернуться.
 *
 * Пустой идентификатор — не ошибка: у части вещей моделей нет, и тогда лучше
 * ничего, чем пустая рамка.
 *
 * $extra — что ещё можно посмотреть из этой же карточки, см. viewer_attrs().
 */
function viewer($modelId, $class = '', $title = '', $desc = '', $extra = null)
{
    if (!$modelId) {
        return '';
    }

    return '<div class="viewer ' . h($class) . '" role="button" tabindex="0"'
        . ' aria-label="Посмотреть модель"' . viewer_attrs($modelId, $title, $desc, $extra) . '>'
        . '<img src="models/' . h($modelId) . '.png?v=' . h(ZM_ASSET_V) . '" alt="" loading="lazy">'
        . '<span class="viewer-open">смотреть в 3D</span>'
        . '</div>';
}

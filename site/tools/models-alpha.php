<?php
/**
 * Вырезание фона у готовых отрисовок моделей.
 *
 * ⚠️ ЗАЧЕМ. build-models.mjs рисует карточную картинку на сплошной подложке
 * цвета #12130f — это был цвет фона сайта в ту пору, когда картинки делались.
 * Пока фон совпадал, подложки не было видно. Оформление сменилось, фон стал
 * другим, да ещё и с красным отсветом, — и под каждой моделью проступил
 * ровный тёмный прямоугольник. Владелец увидел это сразу: «за моделькой видно
 * фон».
 *
 * Здесь подложка становится прозрачной, и картинка ложится на любой фон.
 *
 * ⚠️ ТЕКСТУРЫ НЕ ТРОГАЕМ. Файлы вида имя-0.png и имя-1.png — это НЕ картинки
 * для карточек, а текстуры, которые viewer.js грузит в WebGL (см. loadTexture).
 * Прозрачность в них означает совсем другое: шейдер выбрасывает точки с
 * альфой ниже 0.5 (discard), и «очищенная» текстура превратилась бы в модель
 * с дырами. Поэтому берутся только файлы без числового хвоста.
 *
 * ⚠️ ЕСЛИ ПЕРЕРИСУЕТЕ МОДЕЛИ ЗАНОВО — прогоните это снова, иначе подложка
 * вернётся. Правильное место для такой работы — сам build-models.mjs, но он на
 * Node, а здесь Node не было.
 *
 * Запуск:  php site/tools/models-alpha.php [--dry]
 */

$dir = dirname(__DIR__) . '/public/models';
$dry = in_array('--dry', $argv, true);

if (!extension_loaded('gd')) {
    exit("нужен модуль gd\n");
}

/** Цвет подложки, который кладёт генератор. Один на все отрисовки — проверено. */
const BG = array(0x12, 0x13, 0x0f);

/*
 * Два порога вместо одного.
 *
 * ⚠️ Резать по одному порогу — значит получить рваный контур: у модели края
 * сглажены, и крайние точки наполовину смешаны с подложкой. Отнеси мы их к
 * фону — контур обкусан, к модели — вокруг неё тёмная кайма. Поэтому ниже
 * NEAR точка исчезает совсем, выше FAR остаётся как есть, а между ними
 * прозрачность меняется плавно: сглаживание сохраняется.
 */
const NEAR = 8;    // ближе этого к цвету подложки — это подложка
const FAR  = 48;   // дальше этого — это модель

$done = 0; $skipped = 0;

foreach (glob($dir . '/*.png') as $f) {
    if (preg_match('~-\d+\.png$~', $f)) {
        $skipped++;
        continue;
    }

    $src = @imagecreatefrompng($f);
    if (!$src) {
        printf("%-26s не читается\n", basename($f));
        continue;
    }
    $w = imagesx($src);
    $h = imagesy($src);

    // Проверяем, что подложка та самая: чужую картинку портить нельзя.
    $corner = imagecolorat($src, 0, 0);
    $cr = ($corner >> 16) & 0xFF; $cg = ($corner >> 8) & 0xFF; $cb = $corner & 0xFF;
    if (abs($cr - BG[0]) + abs($cg - BG[1]) + abs($cb - BG[2]) > NEAR) {
        printf("%-26s угол #%02x%02x%02x — не наша подложка, пропускаю\n", basename($f), $cr, $cg, $cb);
        imagedestroy($src);
        continue;
    }

    $out = imagecreatetruecolor($w, $h);
    imagealphablending($out, false);
    imagesavealpha($out, true);
    imagefilledrectangle($out, 0, 0, $w, $h, imagecolorallocatealpha($out, 0, 0, 0, 127));

    $cut = 0;
    for ($y = 0; $y < $h; $y++) {
        for ($x = 0; $x < $w; $x++) {
            $c = imagecolorat($src, $x, $y);
            $r = ($c >> 16) & 0xFF; $g = ($c >> 8) & 0xFF; $b = $c & 0xFF;
            $d = abs($r - BG[0]) + abs($g - BG[1]) + abs($b - BG[2]);

            if ($d <= NEAR) {
                $cut++;
                continue;                       // точка остаётся прозрачной
            }
            // 0 — непрозрачно, 127 — прозрачно: у GD альфа наоборот привычной.
            $a = $d >= FAR ? 0 : (int)round(127 * (1 - ($d - NEAR) / (FAR - NEAR)));
            imagesetpixel($out, $x, $y, imagecolorallocatealpha($out, $r, $g, $b, $a));
        }
    }

    printf("%-26s %dx%d, вырезано %d%% точек\n", basename($f), $w, $h, (int)round($cut / ($w * $h) * 100));

    if (!$dry) {
        imagepng($out, $f, 9);
    }
    imagedestroy($src);
    imagedestroy($out);
    $done++;
}

printf("\nобработано отрисовок: %d, текстур не тронуто: %d\n", $done, $skipped);
echo $dry ? "прогон вхолостую, файлы не изменены\n" : "готово — поднимите ZM_ASSET_V\n";

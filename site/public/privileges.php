}

/**
 * Названия уровней ниже этого — для пометки «плюс всё из …».
 *
 * Пометка называет их поимённо, а не отделывается словом «накопительные»:
 * «плюс всё из VIP и Лидера» покупатель понимает сразу, а «уровни
 * накопительные» ему ещё надо расшифровать.
 */
function lower_tier_names($tiers, $index)
{
    $out = array();
    for ($j = 0; $j < $index; $j++) {
        $out[] = $tiers[$j]['name'];
    }
    return $out;
}

/**
 * Перечисление по-русски: последнее слово через «и», остальные через запятую.
 *
 * ⚠️ Обычный implode(' и ', …) даёт «VIP и Лидер и Император» — так не говорят,
 * и такая строка сразу выдаёт, что фразу собрала машина.
 */
function join_ru($names)
{
    $n = count($names);
    if ($n === 0) {
        return '';
    }
    if ($n === 1) {
        return $names[0];
    }
    $last = array_pop($names);
    return implode(', ', $names) . ' и ' . $last;
}

/** Скорость класса в процентах от обычного зомби: 240 — его скорость в моде. */
function speed_gain($speed)
{
    $d = (int)round(((int)$speed - 240) / 240 * 100);
    return $d ? ' (' . ($d > 0 ? '+' : '') . $d . '%)' : '';
}

/**
 * Таблица сроков — списком пар, а не словарём.
 *
 * ⚠️ Порядок сроков ЗНАЧИМ и хрупок: у terms() ключи числовые (30, 90 и 0 —
 * «навсегда»), а JavaScript в объекте раскладывает числовые ключи по
 * возрастанию, что бы ни прислал PHP. Отдай мы словарь — «навсегда» встало бы
 * первым. Здесь порядок задан положением в массиве, и переставить его молча
 * уже нечему.
 */
function term_list($terms)
{
    $out = array();
    foreach ($terms as $days => $t) {
        $out[] = array('days' => (int)$days, 'label' => $t['label']);
    }
    return $out;
}


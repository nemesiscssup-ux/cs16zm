<?php
/**
 * Защита от запроса, отправленного с чужой страницы.
 *
 * Панель работает по входу с паролем, и браузер прикладывает печенье сессии к
 * ЛЮБОМУ запросу на наш адрес — в том числе к тому, который отправила чужая
 * вкладка. Без этой проверки достаточно заманить вошедшего админа на
 * страницу с невидимой формой, чтобы его руками снять привилегии.
 *
 * Стережём двумя рубежами сразу:
 *   1. одноразовый ключ в теле запроса — чужая страница его не прочитает,
 *      потому что не может прочитать нашу;
 *   2. заголовок Origin — браузер ставит его сам и подделать из скрипта нельзя.
 */

function csrf_token()
{
    if (empty($_SESSION['csrf'])) {
        $_SESSION['csrf'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf'];
}

/**
 * Ключ верен? Сравниваем hash_equals, а не «==»: обычное сравнение обрывается
 * на первом различии, и по времени ответа ключ подбирается посимвольно.
 */
function csrf_ok($given)
{
    return !empty($_SESSION['csrf'])
        && is_string($given)
        && hash_equals($_SESSION['csrf'], $given);
}

/**
 * Запрос пришёл с нашей же страницы?
 *
 * Отсутствие Origin — это переход по ссылке или отправка формы старым
 * браузером, и это нормально. А вот чужой Origin нормальным не бывает.
 *
 * ⚠️⚠️ СТРОКА «null» — ЭТО НЕ ЧУЖОЙ ORIGIN, А СКРЫТЫЙ. На этом панель однажды
 * заперлась целиком, и виноват был не браузер, а мы сами.
 *
 * send_security_headers() ставит на все страницы «Referrer-Policy:
 * no-referrer», а вдобавок у страниц панели стоит тот же <meta name=
 * "referrer">. Chrome при такой политике не просто убирает Referer — он
 * сериализует и Origin как «null», в том числе у формы, отправленной на
 * СВОЙ ЖЕ адрес. Прежнее условие видело непустую строку «null», сравнивало её
 * с «https://zm.hotcs.ru» и отвечало отказом.
 *
 * Со стороны это выглядело так: владелец вводит верный пароль и каждый раз
 * получает «форма устарела — попробуйте ещё раз». Пароль ни при чём, ключ
 * сходился буква в букву — в журнале 12 августа 2026 видно и то и другое:
 *
 *     origin=null проверка_origin=ПРОВАЛ прислано=6cb658e8 в_сессии=6cb658e8 совпало=да
 *
 * Через csrf_guard() ходят ещё и выдача привилегий, и сохранение новостей, так
 * что не работало бы вообще ничего — даже войди он внутрь.
 *
 * ⚠️ Чем платим. «null» умеет прислать и чужая страница — из песочницы iframe
 * или формой с rel="noreferrer". То есть второй рубеж на таких запросах не
 * держит. Держит первый, и он тут главный: одноразовый ключ лежит в сессии, а
 * прочитать нашу страницу чужая не может, и подобрать его не может тоже.
 * Origin здесь — подпорка на случай утечки ключа, и ради неё запирать хозяина
 * снаружи нельзя.
 */
function same_origin()
{
    $origin = isset($_SERVER['HTTP_ORIGIN']) ? (string)$_SERVER['HTTP_ORIGIN'] : '';

    // Пусто — заголовка не было. «null» — он был, но происхождение скрыто.
    // И то и другое означает «сказать нечего», а не «сказано чужое».
    if ($origin === '' || $origin === 'null') {
        return true;
    }

    $host = isset($_SERVER['HTTP_HOST']) ? $_SERVER['HTTP_HOST'] : '';
    $mine = array('https://' . $host, 'http://' . $host);
    return in_array($origin, $mine, true);
}

/** Проверить оба рубежа разом; при провале — оборвать запрос. */
function csrf_guard($given)
{
    if (!same_origin() || !csrf_ok($given)) {
        json_fail('запрос отклонён: обновите страницу и повторите', 403);
    }
}

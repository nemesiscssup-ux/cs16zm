<?php
/**
 * Следы когтей с кровью — рисуются, а не берутся откуда-то.
 *
 * ⚠️ ПОЧЕМУ НЕ КАРТИНКОЙ ИЗ ИНТЕРНЕТА. Весь этот проект начинался с вычистки
 * чужого добра из скачанных сборок: моделей с рекламой, текстур с адресами
 * чужих серверов. Тащить на витрину картинку неизвестного происхождения было
 * бы ровно тем же самым, только своими руками. Здесь всё нарисовано на месте,
 * и права на это ни у кого не спросишь.
 *
 * Устройство простое: каждая царапина — вытянутая линза, проведённая по слегка
 * изогнутому пути. Толщина меняется по синусу, поэтому концы сходятся на нет:
 * коготь входит в поверхность и выходит из неё, а не начинается обрубком.
 * Поверх линзы идёт узкая тёмная сердцевина — это и читается как глубина.
 *
 * Запуск:  php site/tools/claw-marks.php <куда.png> [ширина] [высота]
 */

if (!extension_loaded('gd')) {
    exit("нужен модуль gd\n");
}

$dst = isset($argv[1]) ? $argv[1] : '';
$W   = isset($argv[2]) ? (int)$argv[2] : 520;
$H   = isset($argv[3]) ? (int)$argv[3] : 1300;
if ($dst === '') {
    exit("нужно: <куда.png> [ширина] [высота]\n");
}

$im = imagecreatetruecolor($W, $H);
imagealphablending($im, false);
imagesavealpha($im, true);
imagefilledrectangle($im, 0, 0, $W, $H, imagecolorallocatealpha($im, 0, 0, 0, 127));
imagealphablending($im, true);

/** Смешать два цвета: 0 — первый, 1 — второй. */
function mix($a, $b, $t)
{
    return array(
        (int)round($a[0] + ($b[0] - $a[0]) * $t),
        (int)round($a[1] + ($b[1] - $a[1]) * $t),
        (int)round($a[2] + ($b[2] - $a[2]) * $t),
    );
}

/*
 * Цвета те же, что в оформлении сайта: свежая кровь сверху, запёкшаяся снизу.
 * Своей палитры у картинки нет и быть не должно — иначе она встанет на
 * странице чужой заплаткой.
 */
$fresh = array(0xE8, 0x51, 0x4C);
$dried = array(0x5E, 0x10, 0x13);
$deep  = array(0x12, 0x04, 0x06);

/**
 * Одна царапина.
 *
 * $x0,$y0 — начало, $x1,$y1 — конец, $wide — наибольшая полутолщина,
 * $bend — насколько путь выгибается вбок (без изгиба царапина выглядит
 * начерченной по линейке).
 */
function claw($im, $x0, $y0, $x1, $y1, $wide, $bend, $fresh, $dried, $deep)
{
    $steps = 900;
    for ($i = 0; $i <= $steps; $i++) {
        $t = $i / $steps;
        $x = $x0 + ($x1 - $x0) * $t + sin($t * M_PI) * $bend;
        $y = $y0 + ($y1 - $y0) * $t;

        // Концы сходятся на нет: полутолщина идёт по синусу, а корень делает
        // переход у самых кончиков резче, чтобы они были острыми.
        $half = $wide * pow(sin($t * M_PI), 0.55);
        if ($half < 0.4) {
            continue;
        }

        $c = mix($fresh, $dried, $t);
        $col = imagecolorallocatealpha($im, $c[0], $c[1], $c[2], 12);
        imagefilledellipse($im, (int)$x, (int)$y, (int)($half * 2), 3, $col);

        // Сердцевина — почти чёрная и вдвое уже: это дно борозды.
        $core = $half * 0.42;
        if ($core > 0.6) {
            $cc = imagecolorallocatealpha($im, $deep[0], $deep[1], $deep[2], 30);
            imagefilledellipse($im, (int)$x, (int)$y, (int)($core * 2), 2, $cc);
        }
    }
}

/**
 * Потёк крови: тонкая струйка вниз и капля на конце.
 *
 * ⚠️ Потёк идёт СТРОГО ВНИЗ, как бы ни была наклонена царапина. Кровь течёт по
 * силе тяжести, а не вдоль пореза, и потёк, повторяющий наклон, сразу читается
 * нарисованным.
 */
function drip($im, $x, $y, $len, $wide, $fresh, $dried)
{
    /*
     * ⚠️ СТРУЙКА ДОЛЖНА БЫТЬ ТОНКОЙ. Сперва она рисовалась в две-три ширины
     * пера и вышла бруском: ровная полоса постоянной толщины читается чем
     * угодно, только не стекающей каплей. Кровь на стене оставляет след в
     * пару пикселей, который к низу ещё и сходит на нет.
     */
    for ($i = 0; $i <= $len; $i++) {
        $t = $i / max(1, $len);
        $half = $wide * (1 - $t * 0.55);
        $c = mix($fresh, $dried, 0.45 + $t * 0.55);
        $col = imagecolorallocatealpha($im, $c[0], $c[1], $c[2], 34 + (int)($t * 55));
        imagefilledellipse($im, (int)$x, (int)($y + $i), (int)max(1, round($half)), 2, $col);
    }
    // Капля на конце: она тяжелее струйки и потому шире её, но не полосы.
    $c = mix($fresh, $dried, 0.92);
    $col = imagecolorallocatealpha($im, $c[0], $c[1], $c[2], 42);
    imagefilledellipse($im, (int)$x, (int)($y + $len), (int)max(2, $wide * 1.3), (int)max(3, $wide * 1.9), $col);
}

/*
 * Четыре царапины — как от лапы: расходятся веером, средние длиннее крайних.
 * Числа подобраны на глаз под полосу 520×1300 и пересчитываются от неё, чтобы
 * при другом размере рисунок не рассыпался.
 */
$sx = $W / 520;
$sy = $H / 1300;

$marks = array(
    // x0,   y0,   x1,   y1,  толщина, изгиб
    array(470,  90, 120,  980,  9, -38),
    array(505, 150, 165, 1120, 12, -30),
    array(520, 240, 235, 1210, 10, -22),
    array(500, 330, 330, 1260,  6, -14),
);
foreach ($marks as $m) {
    claw($im, $m[0] * $sx, $m[1] * $sy, $m[2] * $sx, $m[3] * $sy,
         $m[4] * $sx, $m[5] * $sx, $fresh, $dried, $deep);
}

/*
 * Потёки — не по одному на царапину и не в одинаковых местах: правильность
 * здесь и выдаёт рисунок. Точки выбраны врассыпную по длине борозд.
 */
$drips = array(
    array(392, 300, 210, 2.6),
    array(300, 520, 300, 3.2),
    array(238, 700, 160, 2.0),
    array(430, 250, 110, 1.8),
    array(180, 880, 240, 2.8),
    array(345, 430, 130, 1.8),
    array(268, 610,  90, 1.6),
    array(410, 190,  70, 1.5),
    array(205, 790, 130, 2.2),
);
foreach ($drips as $d) {
    drip($im, $d[0] * $sx, $d[1] * $sy, $d[2] * $sy, $d[3] * $sx, $fresh, $dried);
}

imagepng($im, $dst, 9);
printf("%dx%d, царапин %d, потёков %d → %s (%d КБ)\n",
    $W, $H, count($marks), count($drips), basename($dst), (int)(filesize($dst) / 1024));

<?php
/**
 * Архив новостей: всё, что писали, целиком и по порядку.
 *
 * На главной висит та же лента, но короткая и выжимками. Здесь новости лежат
 * ПОЛНОСТЬЮ намеренно: архив — конец пути, дальше читателю идти уже некуда, и
 * прятать от него вторую половину текста за ещё одной ссылкой значит заставить
 * щёлкать ради того, что и так помещается на странице.
 *
 * Просмотрщик моделей этой странице не подключается: крутить здесь нечего, а
 * viewer.js поднимает WebGL и весит больше самой страницы.
 */

require __DIR__ . '/_boot.php';
require_once ZM_APP . '/view.php';
require_once ZM_APP . '/news.php';

send_security_headers();

/** По сколько новостей на странице архива. */
const NEWS_PER_PAGE = 10;

// ── дата по-русски ──────────────────────────────────────────────────────────

/**
 * Дата новости словами: «12 августа 2026».
 *
 * ⚠️ Своя таблица месяцев, а не strftime() и не IntlDateFormatter. Первый
 * зависит от локали операционной системы — русской на хостинге может не
 * оказаться вовсе, и вместо «августа» посетитель увидит «August», — да и
 * объявлен устаревшим. Второму нужно расширение intl, которого на обычном
 * хостинге тоже обычно нет: страница упала бы целиком из-за одной даты.
 * Двенадцать слов в массиве не зависят ни от чего.
 *
 * Строку из базы читаем в часовом поясе сайта; его выставляет bootstrap.php
 * (Europe/Moscow). Без этого новость, написанная в половине первого ночи,
 * показывалась бы вчерашним числом.
 */
function news_date_ru($sqlDate)
{
    $months = array(
        'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
        'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'
    );

    $ts = strtotime((string)$sqlDate);
    if ($ts === false) {
        return '';
    }

    return (int)date('j', $ts) . ' ' . $months[(int)date('n', $ts) - 1] . ' ' . date('Y', $ts);
}

// ── какую страницу показываем ───────────────────────────────────────────────

$total = news_published_count();

// Страница всегда хотя бы одна: на пустом архиве делить нечего, а нулевое
// число страниц ниже увело бы любой номер в перенаправление.
$pages = max(1, (int)ceil($total / NEWS_PER_PAGE));

$page = isset($_GET['p']) ? (int)$_GET['p'] : 1;

/*
 * ⚠️ Номер за границами списка — перенаправление на первую страницу, а не
 * молча показанный первый десяток. Иначе адрес и содержимое расходятся:
 * ?p=99 показывал бы страницу 1, в разбивке горела бы единица, а «назад» и
 * «обновить» возвращали бы то же самое — человек решит, что сайт сломался.
 * Мусор вроде ?p=abc (int) превращает в 0 и уводит сюда же.
 *
 * Зацикливания нет: news.php без ?p — это страница 1, а она в границах всегда.
 */
if ($page < 1 || $page > $pages) {
    redirect('news.php');
}

$items = news_page(NEWS_PER_PAGE, ($page - 1) * NEWS_PER_PAGE);

page_head('Новости', 'news');
?>

<section class="lead">
  <h1>Новости</h1>
  <p class="lead-text">
    Что менялось на сервере: обновления, правила и объявления — свежие сверху.
  </p>
</section>

<?php if (!$items): ?>
  <p class="hint">Пока ничего не писали.</p>
<?php else: ?>

  <div class="news">
    <?php foreach ($items as $n): ?>
      <article class="news-item">
        <div class="news-date"><?= h(news_date_ru($n['published_at'])) ?></div>
        <h2 class="news-title"><?= h($n['title']) ?></h2>
        <?php /* news_html() отдаёт ГОТОВУЮ разметку и уже экранировала текст внутри
                 себя — h() здесь съел бы её собственные <p> и <a>. */ ?>
        <div class="news-body"><?= news_html($n['body']) ?></div>
      </article>
    <?php endforeach; ?>
  </div>

  <?php /*
   * Разбивка показывается только когда страниц больше одной: одинокая кнопка
   * «1» ничего не сообщает и лишь притворяется, что архив продолжается.
   *
   * Номера выведены все подряд, без «…» посередине: новостей у сервера
   * десятки, а не тысячи, и три десятка страниц в этой строке не появятся.
   */ ?>
  <?php if ($pages > 1): ?>
    <nav class="pager" aria-label="Страницы новостей">
      <?php for ($i = 1; $i <= $pages; $i++): ?>
        <?php if ($i === $page): ?>
          <span class="on" aria-current="page"><?= $i ?></span>
        <?php else: ?>
          <?php /* У первой страницы уже есть свой адрес — news.php. Ссылка на
                    ?p=1 завела бы второй адрес того же содержимого. */ ?>
          <a href="<?= $i === 1 ? 'news.php' : '?p=' . $i ?>"><?= $i ?></a>
        <?php endif; ?>
      <?php endfor; ?>
    </nav>
  <?php endif; ?>

<?php endif; ?>

<?php page_foot(); ?>

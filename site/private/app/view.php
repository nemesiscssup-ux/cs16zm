<?php
/*
 * Пульс: красное пятно проступает в случайном месте, бьётся и гаснет.
 *
 * Скрипт живёт здесь, а не в отдельном файле, нарочно: он нужен на КАЖДОЙ
 * странице, а отдельный файл — это лишний запрос на каждой из них ради
 * пятнадцати строк. viewer.js подключают только те страницы, где есть модели,
 * и складывать одно с другим нельзя.
 *
 * ⚠️ Само пятно создаёт скрипт, а не разметка. Если скрипты отключены — не
 * появится ничего, и это правильный исход: пятно ничего не сообщает и ни на
 * что не влияет, а пустой div в разметке остался бы навсегда.
 */
?>
<script>
"use strict";
(function () {
  /*
   * ⚠️ Системная настройка «поменьше движения» — не пожелание, а требование:
   * её включают те, кому от движения на экране физически плохо. Проверяем до
   * того, как что-то создать, а не прячем потом стилем.
   */
  var calm = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)");
  if (calm && calm.matches) { return; }

  var blot = document.createElement("div");
  blot.className = "blot";
  blot.setAttribute("aria-hidden", "true");   // это цвет, а не сообщение
  document.body.appendChild(blot);

  function between(a, b) { return a + Math.random() * (b - a); }

  function beat() {
    // Место и размер меняем, пока пятна не видно, — иначе оно прыгало бы.
    var size = between(26, 54);
    blot.style.width = size + "vmin";
    blot.style.height = size + "vmin";
    // Края нарочно уходят за экран: пятно, всегда целиком видимое, читается
    // как нарисованный кружок, а частью срезанное — как пятно света.
    blot.style.left = between(-12, 92) + "vw";
    blot.style.top = between(-12, 88) + "vh";

    /*
     * ⚠️ Перезапуск анимации требует принудительной перекомпоновки между
     * снятием и возвратом класса. Без чтения offsetWidth браузер сложит обе
     * правки в одну, решит, что класс и не менялся, и анимация проиграет
     * ровно один раз за всю жизнь страницы.
     */
    blot.classList.remove("on");
    void blot.offsetWidth;
    blot.classList.add("on");

    setTimeout(beat, between(5600, 13000));
  }

  setTimeout(beat, between(1500, 4000));
})();
</script>

</body>
</html>
<?php
}


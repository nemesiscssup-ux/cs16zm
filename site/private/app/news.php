<?php
/**
 * Новости: лента для сайта, правка из панели и превращение текста в разметку.
 *
 * Единственное место, где живёт таблица zm_news. Тело новости хранится
 * ОБЫЧНЫМ ТЕКСТОМ, без единого тега: разметку собирает news_html() уже при
 * показе. Так владелец пишет как в письме, а страница не зависит от того, что
 * он когда-то вставил из чужого редактора вместе с невидимой разметкой.
 *
 * ⚠️ published_at тянет две обязанности разом: NULL — черновик, дата — новость
 * видна, и по ней же порядок в ленте. Отдельного «опубликовано: да/нет» нет
 * НАМЕРЕННО — два поля, отвечающих за одно состояние, рано или поздно
 * разойдутся, и в ленте окажется то, чего в панели не видно.
 *
 * Всё, что нужно этому файлу (q/q_row/q_all/q_val и h()), поднимает
 * bootstrap.php ещё до него — своих require здесь нет.
 */

// ── лента ───────────────────────────────────────────────────────────────────

/**
 * Условие видимости и порядок ленты — в одном месте на весь файл.
 *
 * Сравнения published_at с NOW() здесь нарочно нет: отложенной публикации у
 * нас не бывает, а лишнее сравнение молча спрятало бы новость, у которой дата
 * оказалась на минуту впереди.
 *
 * ⚠️ Порядок обязан быть однозначным. Две новости, опубликованные в одну
 * секунду, при сортировке только по published_at встают так, как MySQL решит
 * в этот раз, — и постраничный архив то покажет одну и ту же новость дважды,
 * то потеряет её в стыке между страницами. Добавка id разрешает ничью раз и
 * навсегда.
 */
const NEWS_VISIBLE = 'published_at IS NOT NULL';
const NEWS_ORDER   = 'ORDER BY published_at DESC, id DESC';

/**
 * Последние опубликованные — лента на главной.
 *
 * ⚠️ LIMIT подставляется в текст запроса числом, а не плейсхолдером, и это не
 * небрежность. PDO здесь настроен на настоящие подготовленные запросы
 * (ATTR_EMULATE_PREPARES = false), а q() передаёт все параметры строками —
 * MySQL получит LIMIT '5' и ответит синтаксической ошибкой. Приведение к int
 * до склейки делает подстановку безопасной; ничего другого в этом файле в
 * текст запроса не склеивается.
 */
function news_latest($limit = 5)
{
    $limit = max(1, (int)$limit);

    return q_all(
        'SELECT * FROM zm_news WHERE ' . NEWS_VISIBLE . ' ' . NEWS_ORDER . ' LIMIT ' . $limit
    );
}

/**
 * Страница архива: $offset — сколько новостей пропустить.
 *
 * LIMIT и OFFSET — числами в тексте запроса по той же причине, что в
 * news_latest().
 */
function news_page($limit, $offset)
{
    $limit  = max(1, (int)$limit);
    $offset = max(0, (int)$offset);

    return q_all(
        'SELECT * FROM zm_news WHERE ' . NEWS_VISIBLE . ' ' . NEWS_ORDER
        . ' LIMIT ' . $limit . ' OFFSET ' . $offset
    );
}

/** Сколько новостей видит посетитель — для разбивки архива на страницы. */
function news_published_count()
{
    return (int)q_val('SELECT COUNT(*) FROM zm_news WHERE ' . NEWS_VISIBLE);
}

// ── правка из панели ────────────────────────────────────────────────────────

/**
 * Всё подряд, включая черновики.
 *
 * Черновики идут первыми: это незаконченная работа, к которой возвращаются, а
 * опубликованное листают редко. Постраничной разбивки здесь нет и не нужно —
 * новостей у одного сервера десятки, а не тысячи.
 */
function news_all()
{
    return q_all(
        'SELECT * FROM zm_news
          ORDER BY (published_at IS NULL) DESC, published_at DESC, created_at DESC, id DESC'
    );
}

/** Одна новость по номеру либо null. */
function news_by_id($id)
{
    return q_row('SELECT * FROM zm_news WHERE id = ?', array((int)$id));
}

/**
 * Создать ($id === 0) или переписать новость. Возвращает номер новости.
 *
 * Новая новость всегда рождается ЧЕРНОВИКОМ: published_at остаётся NULL, пока
 * его не поставит news_publish(). Иначе полуготовый текст уезжал бы на главную
 * в ту же секунду, когда его первый раз сохранили.
 *
 * ⚠️ Заголовок режем сами, хотя столбец и так VARCHAR(120): при строгом режиме
 * MySQL слишком длинную строку не подрежет, а откажется писать всю запись — и
 * набранный текст пропадёт вместе с ошибкой, которой посетителю не покажут.
 */
function news_save($id, $title, $body, $author)
{
    $id    = (int)$id;
    $title = mb_substr(trim((string)$title), 0, 120);
    $body  = trim((string)$body);

    if ($id > 0) {
        // Подпись при правке не трогаем: автор — тот, кто новость написал, а
        // не тот, кто последним поправил в ней запятую.
        q(
            'UPDATE zm_news SET title = ?, body = ?, updated_at = NOW() WHERE id = ?',
            array($title, $body, $id)
        );
        return $id;
    }

    q(
        'INSERT INTO zm_news (title, body, author, created_at) VALUES (?, ?, ?, NOW())',
        array($title, $body, (string)$author)
    );

    return (int)db()->lastInsertId();
}

/**
 * Опубликовать ($on истинно) или вернуть в черновики.
 *
 * ⚠️ Повторная публикация ставит СВЕЖУЮ дату и поднимает новость в начало
 * ленты: published_at заодно задаёт порядок, второй даты у ленты нет. Снял,
 * поправил опечатку, вернул — и новость снова наверху. Это прямое следствие
 * одного поля на два смысла (см. заголовок файла), и оно принято сознательно.
 */
function news_publish($id, $on)
{
    $id = (int)$id;

    if ($on) {
        q('UPDATE zm_news SET published_at = NOW() WHERE id = ?', array($id));
    } else {
        q('UPDATE zm_news SET published_at = NULL WHERE id = ?', array($id));
    }
}

/**
 * Удалить насовсем.
 *
 * Корзины нет намеренно: спрятать новость, не теряя текста, и так можно —
 * снять с публикации. Раз есть черновик, второй способ «удалить не совсем»
 * только добавил бы состояний, в которых легко запутаться.
 */
function news_delete($id)
{
    q('DELETE FROM zm_news WHERE id = ?', array((int)$id));
}

// ── текст в разметку ────────────────────────────────────────────────────────

/**
 * Тело новости → готовый HTML.
 *
 * ⚠️ ПОРЯДОК ДЕЙСТВИЙ ЗДЕСЬ И ЕСТЬ ЗАЩИТА, и он ровно такой:
 *     1) h() на весь текст целиком — ДО всякого разбора;
 *     2) абзацы и переводы строк;
 *     3) ссылки, уже по экранированному тексту.
 *
 * Экранировать ПОСЛЕ разбора нельзя ни в каком виде. h() по готовой разметке
 * съест собственные <p> и <a> вместе с чужими тегами — на странице окажется
 * каша из &lt;p&gt;. А стоит свои теги пощадить — хоть заменой обратно, хоть
 * экранированием по кускам «между тегами» — и щель открыта: разметку мы
 * собираем из того же текста, который пишет человек, и отличать «свой» тег от
 * «чужого» после склейки уже нечем. Тело новости приходит из панели, но
 * панель — это вход, а не гарантия: пароль подбирают, сессию угоняют, а
 * строка в базе может появиться и вовсе мимо сайта.
 *
 * Возвращает ГОТОВУЮ разметку: в шаблоне её выводят как есть, без h().
 */
function news_html($body)
{
    // 1. Экранируем целиком. После этой строки в тексте нет ни одного «<» и
    //    ни одной кавычки от человека — только те, что поставим мы сами.
    //    Заодно ENT_SUBSTITUTE меняет битый UTF-8 на «замену»: без этого preg
    //    с /u ниже вернул бы null, и новость показалась бы пустой.
    $safe = h($body);

    // 2. Абзацы. Пустая строка (одна или несколько) начинает новый <p>,
    //    одиночный перевод строки внутри абзаца остаётся переводом строки.
    $out = '';
    foreach (preg_split('/\R{2,}/u', trim($safe)) as $block) {
        $block = trim($block);
        if ($block === '') {
            continue;
        }
        $out .= '<p>' . preg_replace('/\R/u', '<br>', $block) . '</p>';
    }

    // 3. Ссылки — уже по собранной разметке.
    //
    // ⚠️ «<» в наборе [^\s<]+ не украшение: к этому шагу в строке живут наши
    // собственные <br> и </p>, и адрес в конце строки без этого запрета утащил
    // бы «<br>» и весь остаток абзаца внутрь href.
    //
    // Схему требуем явно (http либо https), поэтому «javascript:» в href не
    // попадёт никаким способом. Сам адрес уже экранирован и потому ставится в
    // href="…" как есть: «&» в нём уже «&amp;», кавычка — «&quot;», выйти из
    // атрибута нечем. Это ровно та выгода, ради которой h() шла первой.
    return preg_replace_callback('~https?://[^\s<]+~u', function ($m) {
        // Хвостовая пунктуация в адрес не входит: во фразе «зайдите на
        // http://site.ru.» точка — конец предложения, а не часть ссылки.
        // Кавычку и апостроф ищем в экранированном виде: как символы их в
        // строке уже нет.
        $url  = preg_replace('~(?:[.,!?;:)»…]|&quot;|&#0?39;|&amp;)+$~u', '', $m[0]);
        $tail = mb_substr($m[0], mb_strlen($url));

        // От адреса остался один протокол — значит, ссылки тут и не было.
        if (!preg_match('~^https?://[^\s<]+~u', $url)) {
            return $m[0];
        }

        return '<a href="' . $url . '" rel="noopener noreferrer nofollow">' . $url . '</a>' . $tail;
    }, $out);
}

/**
 * Короткая выжимка для ленты: обычный текст, обрезанный по границе слова.
 *
 * ⚠️ ВОЗВРАЩАЕТ ТЕКСТ, А НЕ РАЗМЕТКУ — в этом её отличие от news_html(), и в
 * шаблоне выжимку обязательно пропускают через h(). Две соседние функции, из
 * которых одна отдаёт готовый HTML, а другая сырой текст, — самое удобное
 * место, чтобы перепутать, поэтому здесь об этом и написано.
 */
function news_excerpt($body, $chars = 200)
{
    // Переводы строк и повторные пробелы схлопываем: абзацы в одну строку
    // витрины всё равно не поместятся, а «дыра» посреди фразы видна сразу.
    $text  = trim(preg_replace('/\s+/u', ' ', (string)$body));
    $chars = max(1, (int)$chars);

    if ($text === '' || mb_strlen($text) <= $chars) {
        return $text;
    }

    $cut   = mb_substr($text, 0, $chars);
    $space = mb_strrpos($cut, ' ');

    // Режем по последнему пробелу, но только если он не в самом начале: у
    // длинного адреса без пробелов ближайший пробел стоит на третьей букве, и
    // от выжимки осталось бы одно слово.
    if ($space !== false && $space >= $chars / 2) {
        $cut = mb_substr($cut, 0, $space);
    }

    // ⚠️ Не rtrim(): его второй аргумент — набор БАЙТОВ, и «—» в нём означает
    // «срезать с конца байты E2, 80 и 94». Байт 0x94 — это хвост буквы «Д»
    // (D0 94), так что rtrim откусил бы у неё половину и оставил в строке
    // битый UTF-8. preg с /u режет символами, а не байтами.
    $cut = preg_replace('/[\s.,;:!?…—–-]+$/u', '', $cut);

    return $cut . '…';
}

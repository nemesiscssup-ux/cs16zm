#!/usr/bin/env bash
# Заливка дерева FastDL на хостинг. Докачиваемая: что уже залито, помнится по
# отпечаткам, а к сайту скрипт идёт только за тем, чего в отпечатках нет.
#
# Почему так: FTP по одному файлу медленный, а обрыв на середине неизбежен при
# 150 файлах. Проверка по HTTP занимает миллисекунды и делает повторный запуск
# дешёвым — можно гонять сколько угодно раз, пока не сойдётся.
#
# Учётные данные берутся из файла netrc, путь к которому передаётся первым
# аргументом: пароль не должен попадать ни в командную строку, ни в репозиторий.
#
# Запуск: tools/upload-fastdl.sh <netrc> <ftp-host> <ftp-путь> <http-база>
#
# ДЛЯ НАШЕГО ХОСТИНГА ровно так (пути проверены, ошибка в них дорого стоит):
#
#   tools/upload-fastdl.sh netrc <адрес-ftp> <каталог> <http-база>
#
# ⚠️ 12 августа 2026 РАЗДАЧА УШЛА С ВЕБ-ХОСТИНГА на игровой: владелец освободил
# место, дерево весило около 260 МБ. Каталог /www/zm.hotcs.ru/cstrike удалён,
# заливать туда больше нечего. Адреса нового места ещё нет — как появится,
# подставлять его сюда и в sv_downloadurl (custom/server-extra.cfg).
#
# Раздача идёт по HTTP: движок GoldSource не умеет ни TLS, ни перенаправлений,
# поэтому в http-базе именно http:// и именно тот адрес, который отдаёт файлы
# сам, без редиректа.
#
# ГРАБЛИ (были верны для веб-хостинга, пригодятся на любом другом): каталог
# сайта — /www/<домен>, а НЕ /public_html (тот в
# домашнем каталоге есть, но наружу не отдаётся). И «cstrike» в конце обоих
# путей не пишем: имена файлов внутри дерева и так начинаются с cstrike/.
# Ошибиться легко, а видно не сразу: проверка по HTTP тогда даёт 404 на всё,
# скрипт считает, что на сайте нет ничего, и заливает все 80 МБ по кругу в
# несуществующий каталог. Именно так и вышло — пришлось убирать за собой.
#
# ВТОРЫЕ ГРАБЛИ: одного размера мало. Файл может измениться ВНУТРИ, не меняя
# длины — так бывает при правке текстуры в модели (tools/mdl-untag.mjs). Из-за
# этого на сайте дважды оставалась старая версия, и владелец видел рекламу,
# которую я уже «убрал». Поэтому помним md5 каждого залитого файла.
#
# ТРЕТЬИ ГРАБЛИ: отпечатки лежат ВЫШЕ dist/fastdl. Внутри неё их стирала
# каждая пересборка дерева, и заливка гнала все триста файлов по кругу —
# а заодно ловила случайные отказы от защиты хостинга по нагрузке.

set -u

NETRC="${1:?нужен путь к netrc}"
HOST="${2:?нужен адрес FTP}"
REMOTE="${3:?нужен каталог на сервере}"
HTTPBASE="${4:?нужен адрес сайта}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)/dist/fastdl"
cd "$ROOT" || { echo "нет каталога $ROOT — сначала node tools/build-fastdl.mjs"; exit 2; }

# Отпечатки того, что уже залито. ВЫШЕ дерева, и это важно: build-fastdl.mjs
# сносит dist/fastdl целиком перед сборкой, поэтому файл внутри неё стирался
# при каждой пересборке — и следующий прогон гнал все триста файлов заново.
STAMPS="$(dirname "$ROOT")/.fastdl-uploaded.md5"
touch "$STAMPS"

ok=0; skip=0; bad=0; i=0
total=$(find cstrike -type f | wc -l)

while IFS= read -r f; do
  i=$((i + 1))

  local_size=$(stat -c%s "$f")

  # СНАЧАЛА отпечаток: он локальный и мгновенный. К сайту идём только там,
  # где отпечатка нет. Перед хостингом стоит защита от нагрузки, и на трёх
  # сотнях запросов она начинает отвечать пустотой — тогда «файл уже есть»
  # читается как «нет», и дерево уезжает по кругу. Именно так и было.
  sum=$(md5sum "$f" | cut -d' ' -f1)
  known=$(grep -F "  $f" "$STAMPS" 2>/dev/null | cut -d' ' -f1)
  if [ -n "$known" ] && [ "$sum" = "$known" ]; then
    skip=$((skip + 1))
    continue
  fi

  # Отпечатка нет — спрашиваем сайт, с повторами и паузой.
  remote_size=""
  for attempt in 1 2 3; do
    remote_size=$(curl -sSkI -m 40 "$HTTPBASE/$f" 2>/dev/null \
      | tr -d '\r' | awk 'tolower($1) == "content-length:" { print $2 }' | tail -1)
    [ -n "$remote_size" ] && break
    sleep 2
  done
  sleep 0.3

  # ⚠️ РАЗМЕРОМ МОЖНО ПОЛЬЗОВАТЬСЯ ТОЛЬКО ТАМ, ГДЕ ОТПЕЧАТКА НЕТ ВОВСЕ.
  # Здесь стояло «-n $known» — и это была ошибка: сюда мы попадаем ровно тогда,
  # когда отпечаток ЕСТЬ и НЕ СОШЁЛСЯ, то есть файл заведомо изменился. А правка
  # одного байта (снятие флага прозрачности у шкуры) длину не меняет, размер
  # совпадает — и изменённый файл молча пропускался. Так одиннадцать
  # исправленных моделей не доехали до хостинга 2026-08-10.
  if [ "${remote_size:-0}" = "$local_size" ] && [ -z "$known" ]; then
    skip=$((skip + 1))
    continue
  fi

  if curl -sS -m 180 --netrc-file "$NETRC" --ftp-create-dirs -T "$f" "ftp://$HOST/$REMOTE/$f" >/dev/null 2>&1; then
    ok=$((ok + 1))
    # Отпечаток записываем ТОЛЬКО после удачной заливки: иначе неудача
    # запомнилась бы как «уже там».
    grep -vF "  $f" "$STAMPS" 2>/dev/null > "$STAMPS.tmp" || true
    echo "$sum  $f" >> "$STAMPS.tmp"
    mv "$STAMPS.tmp" "$STAMPS"
  else
    bad=$((bad + 1))
    echo "  НЕ ЗАЛИТ: $f"
  fi

  if [ $((i % 25)) -eq 0 ]; then
    echo "  ...$i из $total (залито $ok, было $skip)"
  fi
done < <(find cstrike -type f | sort)

echo
echo "итог: залито $ok, уже было $skip, не удалось $bad, всего $total"
[ "$bad" -eq 0 ] || exit 1

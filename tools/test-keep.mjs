// Живая проверка: купленное возвращается в следующем раунде.
//
// ЗАЧЕМ ЖИВОЙ СЕРВЕР. Владелец: «не сохраняются купленные предметы с
// спец-магазина в следующем раунде, и оружия тоже». В апстриме так и задумано —
// вещь живёт один раунд, — и мы это поменяли правкой самого мода. Проверить
// правку чтением исходника нельзя: между «запомнили покупку» и «выдали заново»
// лежит задача, проверка роли и повторный проход через покупку, где вещь может
// молча не выдаться.
//
// ЧЕМ ПРОВЕРЯЕМ. Ночным зрением: это единственная вещь спец-магазина, которую
// умеют покупать БОТЫ (мод сам делает это через десять секунд после
// возрождения). Значит, покупку можно устроить без живого игрока.
//
// ⚠️ ОКНО ПРОВЕРКИ. Свою покупку бот делает на десятой секунде, а возврат
// купленного приходит на первой. Поэтому смотрим на третьей: если свет есть,
// его вернули мы, а не бот купил заново.
//
// Запуск: node tools/test-keep.mjs

import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { start, stopAll } from './live.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const wait = ms => new Promise(r => setTimeout(r, ms))

let ok = 0
let bad = 0
function check(name, pass, detail = '') {
  if (pass) { ok++; console.log(`[ ОК  ] ${name}${detail ? `\n       ${detail}` : ''}`) }
  else { bad++; console.log(`[ НЕТ ] ${name}${detail ? `\n       ${detail}` : ''}`) }
}

const TARGET = '#2'   // бот, за которым следим

const server = await start({ map: 'de_dust2', bots: 6 })
try {
  const { rcon } = server
  await wait(4000)

  const info = async () => {
    const out = await rcon.run(`zp_ability_info ${TARGET}`)
    return {
      packs: Number((out.match(/кредиты=(-?\d+)/) ?? [])[1] ?? -1),
      light: (out.match(/свет=(\d)/) ?? [])[1] === '1',
      zombie: /зомби=1/.test(out),
    }
  }

  // ⚠️ ЗАРАЖЕНИЕ ОТОДВИГАЕМ. По умолчанию первое заражение приходит на десятой
  // секунде — ровно тогда же, когда бот покупает. Зомби ночное зрение мод даёт
  // ДАРОМ, и проверка приняла бы его за покупку: первый прогон именно на этом
  // и обманулся, показав «купил» при нетронутых кредитах.
  await rcon.run('zp_delay 45')

  // Ночное зрение стоит 15, а на входе дают 5 — иначе бот не купит ничего и
  // проверять будет нечего.
  await rcon.run(`zp_packs ${TARGET} 200`)
  await rcon.run('sv_restart 1')

  // ⚠️ ЖДЁМ ДОЛЬШЕ, ЧЕМ КАЖЕТСЯ НУЖНЫМ, И ПЕРЕЧИТЫВАЕМ КОШЕЛЁК. Кредиты теперь
  // приезжают ИЗ БАЗЫ через три секунды после захода и перекрывают выданные
  // нами. Проверка, сравнивавшая с числом 200, из-за этого решила, что покупки
  // не было: на боте оказалась его сохранённая сумма.
  await wait(6000)
  const before = (await info()).packs

  // ⚠️ ЖДАТЬ ДОЛГО И ЭТО НОРМАЛЬНО. Мод ставит боту покупку на «десятая секунда
  // ПЛЮС задержка заражения», то есть при zp_delay 45 — на пятьдесят пятой.
  // Тридцати секунд не хватало, и проверка врала, будто покупки не случилось.
  await wait(45000)

  // ⚠️⚠️ И ДЕРЖИМ ПОДОПЫТНОГО ЧЕЛОВЕКОМ. Покупка приходит на восемь секунд
  // ПОЗЖЕ первого заражения — так устроен сам мод, — а зомби не покупает
  // ничего: bot_buy_extras выходит на первой же строке. Если нашего бота
  // успели заразить, ждать можно вечно. Поэтому назначаем зомби двух других и
  // возвращаем его в люди прямо перед покупкой.
  await rcon.run('zp_zombie #3')
  await rcon.run('zp_zombie #4')
  await rcon.run(`zp_human ${TARGET}`)

  // Ждём ИМЕННО ПОКУПКУ: живой человек, свет есть, кредитов стало меньше.
  // Любого из трёх условий по отдельности мало.
  let bought = null
  for (let i = 0; i < 40 && !bought; i++) {
    await wait(1000)
    const cur = await info()
    if (!cur.zombie && cur.light && cur.packs < before) bought = cur
  }
  check('бот купил ночное зрение', bought !== null,
    bought ? `кредитов осталось ${bought.packs} из ${before}` : 'покупки не случилось: бот так и не купил свет')

  if (bought) {
    // Новый раунд. Мод раздевает всех и сбрасывает переменные игрока — в
    // апстриме на этом купленное и пропадало.
    await rcon.run('sv_restart 1')
    await wait(3000)

    const after = await info()
    check('купленное вернулось в новом раунде', after.light && !after.zombie,
      after.light && !after.zombie ? 'свет на месте через три секунды после начала раунда'
        : `света нет — возврат покупок не сработал (зомби=${after.zombie ? 1 : 0})`)

    // Возврат обязан быть бесплатным: иначе за одну покупку игрок платил бы
    // каждый раунд, и это было бы хуже прежнего поведения.
    check('за возврат не списали кредиты второй раз', after.packs >= bought.packs,
      `было ${bought.packs}, стало ${after.packs}`)
  }
} finally {
  await stopAll()
}

console.log(`\nитог: ${ok} из ${ok + bad} проверок пройдено`)
process.exit(bad ? 1 : 0)
